-- 4. Document Metadata Tracking Table
CREATE OR REPLACE TABLE MTGDOC (
    DOC_ID          INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    APP_ID          INT NOT NULL REFERENCES MTGAPP(APP_ID) ON DELETE CASCADE,
    DOC_TYPE        VARCHAR(30)  NOT NULL, -- 'PAYSLIP', 'BANK_STATEMENT', 'ID_PASSPORT'
    FILE_NAME       VARCHAR(100) NOT NULL,
    VERIFIED_FLAG   CHAR(1)      NOT NULL DEFAULT 'N',
    UPLOADED_TS     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 5. Underwriting Decision History Table
CREATE OR REPLACE TABLE MTGDEC (
    DEC_ID          INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    APP_ID          INT NOT NULL REFERENCES MTGAPP(APP_ID) ON DELETE CASCADE,
    DECISION_CODE   VARCHAR(10)  NOT NULL, -- 'APPROVED', 'REFERRED', 'DECLINED'
    REASON_CODE     VARCHAR(30)  NOT NULL,
    REASON_DESC     VARCHAR(120) NOT NULL,
    MAX_LOAN        DECIMAL(11,2) NOT NULL DEFAULT 0.00,
    DECISION_TS     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 6. Application Output & Event Audit Log Table
CREATE OR REPLACE TABLE MTGAUDIT (
    AUDIT_ID        INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    APP_ID          INT NOT NULL DEFAULT 0,
    ACTION_VERB     VARCHAR(30)   NOT NULL,
    HTTP_STATUS     INT           NOT NULL DEFAULT 200,
    STATUS_CODE     VARCHAR(20)   NOT NULL DEFAULT '',
    OUTPUT_PAYLOAD  VARCHAR(4000) NOT NULL DEFAULT '',
    USER_PROFILE    VARCHAR(18)   NOT NULL DEFAULT USER,
    JOB_NAME        VARCHAR(28)   NOT NULL DEFAULT '',
    LOGGED_TS       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
