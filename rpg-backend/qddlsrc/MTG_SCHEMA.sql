-- =====================================================================
-- Database Schema for IBM i Mortgage Demo Showcase
-- Target DBMS: IBM Db2 for i
-- =====================================================================

-- 1. Application Master Table
CREATE OR REPLACE TABLE MTGAPP (
    APP_ID          INT GENERATED ALWAYS AS IDENTITY (START WITH 1001 INCREMENT BY 1) PRIMARY KEY,
    CUST_NAME       VARCHAR(80)   NOT NULL,
    APP_TYPE        VARCHAR(20)   NOT NULL DEFAULT 'FIRST_TIME', -- 'FIRST_TIME', 'MOVER', 'REMORTGAGE'
    STATUS          VARCHAR(20)   NOT NULL DEFAULT 'DRAFT',      -- 'DRAFT', 'SUBMITTED', 'APPROVED', 'REFERRED', 'DECLINED'
    PROP_VALUE      DECIMAL(11,2) NOT NULL DEFAULT 0.00,
    LOAN_AMT        DECIMAL(11,2) NOT NULL DEFAULT 0.00,
    TERM_YRS        INT           NOT NULL DEFAULT 25,
    PROD_ID         VARCHAR(10)   NOT NULL DEFAULT '',
    INT_RATE        DECIMAL(5,2)  NOT NULL DEFAULT 0.00,
    MONTHLY_PMT     DECIMAL(9,2)  NOT NULL DEFAULT 0.00,
    CREATED_TS      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_TS      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Applicant Financial Profile Table
CREATE OR REPLACE TABLE MTGFIN (
    APP_ID          INT PRIMARY KEY REFERENCES MTGAPP(APP_ID) ON DELETE CASCADE,
    GROSS_INCOME    DECIMAL(11,2) NOT NULL DEFAULT 0.00,
    OTHER_INCOME    DECIMAL(11,2) NOT NULL DEFAULT 0.00,
    MONTHLY_EXP     DECIMAL(9,2)  NOT NULL DEFAULT 0.00,
    EXISTING_DEBTS  DECIMAL(9,2)  NOT NULL DEFAULT 0.00,
    CREDIT_SCORE    INT           NOT NULL DEFAULT 720,
    EMPLOYMENT_STS  VARCHAR(30)   NOT NULL DEFAULT 'PERMANENT_FT'
);

-- 3. Mortgage Product Catalog Table
CREATE OR REPLACE TABLE MTGPRD (
    PROD_ID         VARCHAR(10) PRIMARY KEY,
    PROD_NAME       VARCHAR(60)   NOT NULL,
    RATE_TYPE       VARCHAR(20)   NOT NULL, -- 'FIXED_2YR', 'FIXED_5YR', 'VARIABLE'
    INITIAL_RATE    DECIMAL(5,2)  NOT NULL,
    MAX_LTV         DECIMAL(5,2)  NOT NULL,
    FEE             DECIMAL(7,2)  NOT NULL DEFAULT 0.00,
    DESCRIPTION     VARCHAR(120)  NOT NULL DEFAULT ''
);

